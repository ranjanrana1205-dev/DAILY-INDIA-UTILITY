const storageKeys = {
  language: "daily-india-language",
  reminders: "daily-india-vehicle-reminders",
  checklist: "daily-india-vehicle-checklist"
};
let language = localStorage.getItem(storageKeys.language) === "hi" ? "hi" : "en";
let reminderStorageError = false;
let checklistStorageError = false;
let reminders = loadReminders();

function t(key) {
  return travelCopy[language][key];
}

function formatNumber(value, digits = 2) {
  return new Intl.NumberFormat(language === "hi" ? "hi-IN" : "en-IN", {
    maximumFractionDigits: digits
  }).format(value);
}

function formatRupees(value) {
  return new Intl.NumberFormat(language === "hi" ? "hi-IN" : "en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2
  }).format(value);
}

function setResult(id, message) {
  document.getElementById(id).textContent = message;
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.body.classList.toggle("lang-hi", language === "hi");
  document.querySelectorAll("[data-travel-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.travelI18n);
  });
  document.getElementById("languageSwitch").setAttribute(
    "aria-label",
    language === "en" ? "Switch to Hindi" : "Switch to English"
  );
  document.getElementById("currentYear").textContent = new Date().getFullYear();
  renderChecklist();
  renderReminders();
}

function loadReminders() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKeys.reminders) || "[]");
    if (!Array.isArray(saved)) return [];
    return saved.filter((item) => item && typeof item.id === "string" &&
      typeof item.vehicle === "string" && typeof item.service === "string" &&
      typeof item.date === "string");
  } catch {
    reminderStorageError = true;
    return [];
  }
}

function onSubmit(formId, callback) {
  document.getElementById(formId).addEventListener("submit", (event) => {
    event.preventDefault();
    callback(new FormData(event.currentTarget));
  });
}

onSubmit("mileageForm", (data) => {
  const mileage = Number(data.get("distance")) / Number(data.get("fuel"));
  setResult("mileageResult", `${t("mileage")}: ${formatNumber(mileage)} ${t("mileageUnit")}`);
});

function calculateFuel(data) {
  const distance = Number(data.get("distance"));
  const fuelAmount = distance / Number(data.get("mileage"));
  const fuelCost = fuelAmount * Number(data.get("price"));
  return { fuelAmount, fuelCost };
}

onSubmit("fuelForm", (data) => {
  const { fuelAmount, fuelCost } = calculateFuel(data, false);
  const unit = language === "hi" ? "लीटर / किलो" : "L / kg";
  setResult("fuelResult", `${t("fuelUsedEstimate")}: ${formatNumber(fuelAmount)} ${unit} · ${t("fuelCost")}: ${formatRupees(fuelCost)}`);
});

onSubmit("tripForm", (data) => {
  const { fuelCost } = calculateFuel(data, true);
  const total = fuelCost + Number(data.get("tolls")) + Number(data.get("other"));
  const travelers = Number(data.get("people"));
  setResult("tripResult", `${t("tripTotal")}: ${formatRupees(total)} · ${t("perPerson")}: ${formatRupees(total / travelers)}`);
});

onSubmit("distanceForm", (data) => {
  const radians = (degrees) => degrees * Math.PI / 180;
  const lat1 = radians(Number(data.get("lat1")));
  const lat2 = radians(Number(data.get("lat2")));
  const latitudeDiff = lat2 - lat1;
  const longitudeDiff = radians(Number(data.get("lon2")) - Number(data.get("lon1")));
  const a = Math.min(1, Math.sin(latitudeDiff / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(longitudeDiff / 2) ** 2);
  const distanceKm = 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  setResult("distanceResult", `${t("straightDistance")}: ${formatNumber(distanceKm)} km`);
});

function renderReminders() {
  const list = document.getElementById("maintenanceList");
  list.replaceChildren();
  const status = document.getElementById("maintenanceStatus");
  status.textContent = reminderStorageError ? t("maintenanceStorageError") : "";
  if (!reminders.length) {
    const empty = document.createElement("li");
    empty.className = "student-note";
    empty.textContent = t("noReminders");
    list.append(empty);
    return;
  }
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  reminders.slice().sort((a, b) => a.date.localeCompare(b.date)).forEach((reminder) => {
    const item = document.createElement("li");
    item.className = "timetable-item";
    const description = document.createElement("span");
    const dueDate = new Date(`${reminder.date}T00:00:00`);
    const dueLabel = dueDate < today ? t("overdue") : t("due");
    const odometer = reminder.odometer ? ` · ${t("dueAt")} ${formatNumber(Number(reminder.odometer), 0)} km` : "";
    description.textContent = `${reminder.vehicle} · ${reminder.service} · ${dueLabel}: ${reminder.date}${odometer}`;
    const remove = document.createElement("button");
    remove.type = "button";
    remove.dataset.removeReminder = reminder.id;
    remove.textContent = t("removeReminder");
    item.append(description, remove);
    list.append(item);
  });
}

document.getElementById("maintenanceForm").addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const reminder = {
    id: `${Date.now()}-${Math.random().toString(36).slice(2)}`,
    vehicle: form.elements.vehicle.value.trim(),
    service: form.elements.service.value.trim(),
    date: form.elements.date.value,
    odometer: form.elements.odometer.value
  };
  reminders.push(reminder);
  try {
    localStorage.setItem(storageKeys.reminders, JSON.stringify(reminders));
    reminderStorageError = false;
  } catch {
    reminders.pop();
    reminderStorageError = true;
    renderReminders();
    return;
  }
  form.reset();
  renderReminders();
});

document.getElementById("maintenanceList").addEventListener("click", (event) => {
  const button = event.target.closest("[data-remove-reminder]");
  if (!button) return;
  const previous = reminders;
  reminders = reminders.filter((reminder) => reminder.id !== button.dataset.removeReminder);
  try {
    localStorage.setItem(storageKeys.reminders, JSON.stringify(reminders));
    reminderStorageError = false;
  } catch {
    reminders = previous;
    reminderStorageError = true;
  }
  renderReminders();
});

function loadChecklist() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKeys.checklist) || "{}");
    return saved && typeof saved === "object" && !Array.isArray(saved) ? saved : {};
  } catch {
    checklistStorageError = true;
    return {};
  }
}

function renderChecklist() {
  const container = document.getElementById("vehicleChecklist");
  const saved = loadChecklist();
  container.replaceChildren();
  t("checkItems").forEach((key) => {
    const label = document.createElement("label");
    label.className = "vehicle-check-item";
    const checkbox = document.createElement("input");
    checkbox.type = "checkbox";
    checkbox.dataset.checkItem = key;
    checkbox.checked = saved[key] === true;
    const caption = document.createElement("span");
    caption.textContent = t(key);
    label.append(checkbox, caption);
    container.append(label);
  });
  const status = document.getElementById("checklistStatus");
  if (status) status.textContent = checklistStorageError ? t("checklistStorageError") : t("checklistSaved");
}

document.getElementById("vehicleChecklist").addEventListener("change", (event) => {
  const checkbox = event.target.closest("[data-check-item]");
  if (!checkbox) return;
  const saved = loadChecklist();
  saved[checkbox.dataset.checkItem] = checkbox.checked;
  try {
    localStorage.setItem(storageKeys.checklist, JSON.stringify(saved));
    checklistStorageError = false;
  } catch {
    checklistStorageError = true;
  }
  const status = document.getElementById("checklistStatus");
  status.textContent = checklistStorageError ? t("checklistStorageError") : t("checklistSaved");
});

document.getElementById("languageSwitch").addEventListener("click", () => {
  language = language === "en" ? "hi" : "en";
  localStorage.setItem(storageKeys.language, language);
  applyLanguage();
});

document.getElementById("currentYear").textContent = new Date().getFullYear();
applyLanguage();
