const checklistItems = ["identityDoc", "addressDoc", "birthDoc", "photoDoc", "contactDoc", "applicationDoc"];
let language = "en";
let checklistStorageError = false;
let languageStorageError = false;
const searchInput = document.getElementById("serviceSearch");
const serviceGrid = document.getElementById("governmentServiceGrid");
const checklistContainer = document.getElementById("governmentChecklist");

function t(key) {
  return governmentCopy[language][key];
}

function readChecklist() {
  try {
    const saved = JSON.parse(localStorage.getItem(checklistKey) || "{}");
    if (!saved || typeof saved !== "object" || Array.isArray(saved)) throw new TypeError("Invalid checklist data");
    return Object.fromEntries(checklistItems.map((key) => [key, saved[key] === true]));
  } catch {
    checklistStorageError = true;
    return Object.fromEntries(checklistItems.map((key) => [key, false]));
  }
}

function updateChecklistStatus() {
  const status = document.getElementById("checklistStatus");
  status.textContent = checklistStorageError
    ? t("checklistStorageError")
    : languageStorageError ? t("languageStorageError") : t("checklistSaved");
}

function renderServices() {
  const query = searchInput.value.trim().toLocaleLowerCase();
  serviceGrid.replaceChildren();
  const visibleServices = services.filter((service) => {
    const searchText = [
      t(`${service.id}Title`), t(`${service.id}Description`),
      governmentCopy[language].serviceTags[service.id],
      ...service.links.map(([, key]) => t(key))
    ].join(" ").toLocaleLowerCase();
    return searchText.includes(query);
  });

  visibleServices.forEach((service) => {
    const card = document.createElement("article");
    card.className = "student-card government-service-card";
    const heading = document.createElement("div");
    heading.className = "student-card-heading";
    const icon = document.createElement("span");
    icon.className = `student-tool-icon ${service.id === "jobs" ? "tone-orange" : "tone-green"}`;
    icon.setAttribute("aria-hidden", "true");
    icon.textContent = service.icon;
    const headingCopy = document.createElement("div");
    const title = document.createElement("h2");
    title.textContent = t(`${service.id}Title`);
    const description = document.createElement("p");
    description.textContent = t(`${service.id}Description`);
    headingCopy.append(title, description);
    heading.append(icon, headingCopy);
    card.append(heading);

    service.links.forEach(([url, key]) => {
      const link = document.createElement("a");
      link.className = service.internal ? "student-action-link" : "student-resource-link";
      link.href = service.internal ? "#governmentChecklist" : url;
      if (!service.internal) {
        link.target = "_blank";
        link.rel = "noopener noreferrer";
      }
      link.textContent = t(key);
      card.append(link);
    });

    if (service.note) {
      const note = document.createElement("p");
      note.className = "student-note";
      note.textContent = t(service.note);
      card.append(note);
    }
    serviceGrid.append(card);
  });

  document.getElementById("serviceEmpty").hidden = visibleServices.length > 0;
  document.getElementById("serviceCount").textContent = `${visibleServices.length} ${language === "hi" ? "सेवाएँ" : "services"}`;
}

function renderChecklist() {
  const saved = readChecklist();
  checklistContainer.replaceChildren();
  checklistItems.forEach((key) => {
    const label = document.createElement("label");
    label.className = "vehicle-check-item";
    const checkbox = document.createElement("input");
    checkbox.type = "checkbox";
    checkbox.dataset.checkItem = key;
    checkbox.checked = saved[key];
    const text = document.createElement("span");
    text.textContent = t(key);
    label.append(checkbox, text);
    checklistContainer.append(label);
  });
  updateChecklistStatus();
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.body.classList.toggle("lang-hi", language === "hi");
  document.querySelectorAll("[data-gov-i18n]").forEach((element) => {
    const value = t(element.dataset.govI18n);
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-gov-placeholder]").forEach((element) => {
    const value = t(element.dataset.govPlaceholder);
    if (value) element.placeholder = value;
  });
  searchInput.setAttribute("aria-label", t("searchLabel"));
  document.getElementById("languageSwitch").setAttribute("aria-label", language === "en" ? "Switch to Hindi" : "Switch to English");
  document.getElementById("currentYear").textContent = new Date().getFullYear();
  renderServices();
  renderChecklist();
}

try {
  language = localStorage.getItem(languageKey) === "hi" ? "hi" : "en";
} catch {
  languageStorageError = true;
}

searchInput.addEventListener("input", renderServices);
checklistContainer.addEventListener("change", (event) => {
  const checkbox = event.target.closest("[data-check-item]");
  if (!checkbox) return;
  const saved = readChecklist();
  saved[checkbox.dataset.checkItem] = checkbox.checked;
  try {
    localStorage.setItem(checklistKey, JSON.stringify(saved));
    checklistStorageError = false;
  } catch {
    checklistStorageError = true;
  }
  updateChecklistStatus();
});

document.getElementById("languageSwitch").addEventListener("click", () => {
  language = language === "en" ? "hi" : "en";
  try {
    localStorage.setItem(languageKey, language);
    languageStorageError = false;
  } catch {
    languageStorageError = true;
  }
  applyLanguage();
});

applyLanguage();
