function selectTool(id) {
  const tool = getTool(id);
  if (!tool) return;
  const recent = getSavedIds("daily-india-recent").filter((recentId) => recentId !== id);
  recent.unshift(id);
  saveIds("daily-india-recent", recent.slice(0, 12));
  renderDashboard();
  if (calculatorSpecs[id]) {
    openCalculator(id);
    return;
  }
  showToast(`${toolName(tool)} — ${t("selectedTool")}`);
}

