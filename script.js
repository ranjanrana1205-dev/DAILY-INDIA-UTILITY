const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
const voiceSearchButton = document.getElementById("voiceSearch");
voiceSearchButton.addEventListener("click", () => {
  if (!SpeechRecognition) {
    document.getElementById("voiceSearchStatus").textContent = t("voiceUnsupported");
    return;
  }
  const recognition = new SpeechRecognition();
  recognition.lang = language === "hi" ? "hi-IN" : "en-IN";
  recognition.interimResults = false;
  recognition.maxAlternatives = 1;
  document.getElementById("voiceSearchStatus").textContent = t("voiceListening");
  recognition.addEventListener("result", (event) => {
    const transcript = event.results[0][0].transcript.trim();
    if (!transcript) {
      document.getElementById("voiceSearchStatus").textContent = t("voiceNoSpeech");
      return;
    }
    searchInput.value = transcript;
    document.getElementById("searchForm").requestSubmit();
  });
  recognition.addEventListener("error", () => {
    document.getElementById("voiceSearchStatus").textContent = t("voiceFailed");
  });
  recognition.addEventListener("nomatch", () => {
    document.getElementById("voiceSearchStatus").textContent = t("voiceNoSpeech");
  });
  try {
    recognition.start();
  } catch {
    document.getElementById("voiceSearchStatus").textContent = t("voiceFailed");
  }
});

