function getSavedIds(key) {
  try {
    const saved = JSON.parse(localStorage.getItem(key) || "[]");
    return Array.isArray(saved) ? [...new Set(saved.filter((id) => getTool(id)))].slice(0, 20) : [];
  } catch {
    return [];
  }
}

function saveIds(key, ids) {
  try {
    localStorage.setItem(key, JSON.stringify(ids));
    return true;
  } catch {
    showToast(t("localSaveError"));
    return false;
  }
}

function renderDashboardList(containerId, ids, emptyText, withFavorites = false) {
  const container = document.getElementById(containerId);
  container.replaceChildren();
  const validTools = ids.map(getTool).filter(Boolean);
  if (!validTools.length) {
    const empty = document.createElement("p");
    empty.className = "dashboard-empty";
    empty.textContent = emptyText;
    container.append(empty);
    return;
  }
  validTools.forEach((tool) => {
    const row = document.createElement("div");
    row.className = "dashboard-tool-row";
    const open = document.createElement("button");
    open.className = "dashboard-tool-open";
    open.type = "button";
    open.dataset.tool = tool.id;
    const icon = document.createElement("span");
    icon.className = `tool-icon tone-${tool.tone}`;
    icon.textContent = tool.icon;
    const name = document.createElement("strong");
    name.textContent = toolName(tool);
    open.append(icon, name);
    row.append(open);
    if (withFavorites) {
      const remove = document.createElement("button");
      remove.type = "button";
      remove.className = "favorite-toggle is-favorite";
      remove.dataset.favorite = tool.id;
      remove.setAttribute("aria-label", t("unfavorite"));
      remove.setAttribute("aria-pressed", "true");
      remove.title = t("unfavorite");
      remove.textContent = "★";
      row.append(remove);
    }
    container.append(row);
  });
}

function renderDashboard() {
  const favorites = getSavedIds("daily-india-favorites");
  const history = getSavedIds("daily-india-recent");
  renderDashboardList("favoritesList", favorites, t("emptyFavorites"), true);
  renderDashboardList("historyList", history, t("emptyHistory"));
  const preferredCategories = [...favorites, ...history].map(getTool).filter(Boolean).map((tool) => tool.category);
  const categoryCounts = preferredCategories.reduce((counts, category, index) => {
    counts[category] = (counts[category] || 0) + (index < favorites.length ? 2 : 1);
    return counts;
  }, {});
  const recommendations = tools
    .filter((tool) => !favorites.includes(tool.id))
    .sort((left, right) =>
      (categoryCounts[right.category] || 0) - (categoryCounts[left.category] || 0)
      || Number(right.trending) - Number(left.trending)
      || left.name.localeCompare(right.name)
    )
    .slice(0, 3);
  renderDashboardList("recommendationsList", recommendations.map((tool) => tool.id), t("assistantEmpty"));
}

function renderCalculatorDialog(id) {
  const tool = getTool(id);
  const spec = calculatorSpecs[id];
  if (!tool || !spec) return;
  document.getElementById("calculatorDialogTitle").textContent = toolName(tool);
  document.getElementById("calculatorDialogDescription").textContent = toolDescription(tool);
  const fields = document.getElementById("calculatorFields");
  fields.replaceChildren();
  spec.fields.forEach((field, index) => {
    const label = document.createElement("label");
    label.className = "calculator-field";
    label.htmlFor = `calculator-input-${index}`;
    label.textContent = t("calculatorLabels")[field.key];
    let control;
    if (field.type === "select") {
      control = document.createElement("select");
      field.choices.forEach(([labelKey, value]) => {
        const option = document.createElement("option");
        option.value = value;
        option.textContent = field.key === "compounding"
          ? t("frequencies")[Number(labelKey)]
          : t("calculatorLabels")[labelKey];
        control.append(option);
      });
    } else {
      control = document.createElement("input");
      control.type = field.type;
      if (field.type === "number") control.inputMode = "decimal";
      if (field.type === "date") {
        const today = new Date();
        control.max = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}-${String(today.getDate()).padStart(2, "0")}`;
        control.addEventListener("input", () => control.setCustomValidity(""));
      }
      if (field.min !== undefined) control.min = field.min;
      if (field.max !== undefined) control.max = field.max;
      if (field.step !== undefined) control.step = field.step;
    }
    control.id = label.htmlFor;
    control.name = field.key;
    control.required = true;
    if (field.value !== undefined) control.value = field.value;
    label.append(control);
    fields.append(label);
  });
  const note = document.getElementById("calculatorNote");
  note.hidden = !spec.note;
  note.textContent = spec.note ? t("calculatorNotes")[spec.note] : "";
  document.getElementById("calculatorResult").hidden = true;
  document.getElementById("calculatorResultContent").replaceChildren();
}

function formatRupees(amount) {
  return new Intl.NumberFormat(language === "hi" ? "hi-IN" : "en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 2
  }).format(amount);
}

function showCalculatorResult(results) {
  const content = document.getElementById("calculatorResultContent");
  content.replaceChildren();
  results.forEach(([key, value]) => {
    const row = document.createElement("div");
    row.className = "calculator-result-row";
    const label = document.createElement("span");
    label.textContent = t("calculatorResults")[key];
    const output = document.createElement("strong");
    output.textContent = typeof value === "number" ? formatRupees(value) : value;
    row.append(label, output);
    content.append(row);
  });
  document.getElementById("calculatorResult").hidden = false;
}

