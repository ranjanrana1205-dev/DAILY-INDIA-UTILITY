function calculateActiveTool(event) {
  event.preventDefault();
  const spec = calculatorSpecs[activeCalculatorId];
  if (!spec) return;
  const values = {};
  spec.fields.forEach((field) => {
    const input = document.getElementById(`calculator-input-${spec.fields.indexOf(field)}`);
    input.setCustomValidity("");
    values[field.key] = field.type === "select" ? input.value : field.type === "number" ? Number(input.value) : input.value;
  });
  if (activeCalculatorId === "age") {
    const birthInput = document.getElementById("calculator-input-0");
    const birth = new Date(`${values.birthDate}T00:00:00`);
    if (!values.birthDate || Number.isNaN(birth.getTime()) || birth > new Date()) {
      birthInput.setCustomValidity(language === "hi" ? "कृपया पिछली मान्य तारीख दर्ज करें।" : "Enter a valid date in the past.");
      birthInput.reportValidity();
      return;
    }
  }
  showCalculatorResult(spec.calculate(values));
}

